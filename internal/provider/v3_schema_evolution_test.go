// v3SurfaceBaselinePath is the committed floor the evolution rule is measured
// against. It is hand-committed, never regenerated by a gate: a baseline a gate
// rewrites is a baseline that agrees with every change.
const v3SurfaceBaselinePath = "testdata/v3-schema-baseline.json"

// v3AttributeSurface is what the framework exposes about one attribute and what
// the rule is decidable over. Validators are deliberately absent: the framework
// gives no comparable rendering of one, and "relaxing validation" is allowed
// anyway, so a baseline that tried to pin them would only forbid the permitted
// direction.
type v3AttributeSurface struct {
	Type      string `json:"type"`
	Required  bool   `json:"required"`
	Optional  bool   `json:"optional"`
	Computed  bool   `json:"computed"`
	Sensitive bool   `json:"sensitive,omitempty"`
}

type v3ResourceSurface struct {
	Version    int64                         `json:"version"`
	Attributes map[string]v3AttributeSurface `json:"attributes"`
}

func v3CurrentSurface(t *testing.T) map[string]v3ResourceSurface {
	t.Helper()
	ctx := context.Background()
	surface := map[string]v3ResourceSurface{}
	for _, form := range edgeformcatalog.Forms {
		resource := v3Provider3CurrentResourceHarness(t, form, "", nil, v3Codecs())
		var response frameworkresource.SchemaResponse
		resource.Schema(ctx, frameworkresource.SchemaRequest{}, &response)
		if response.Diagnostics.HasError() {
			t.Fatalf("%s schema: %v", form.Kind, response.Diagnostics)
		}
		attributes := map[string]v3AttributeSurface{}
		for name, attribute := range response.Schema.Attributes {
			attributes[name] = v3AttributeSurface{
				Type:      attribute.GetType().String(),
				Required:  attribute.IsRequired(),
				Optional:  attribute.IsOptional(),
				Computed:  attribute.IsComputed(),
				Sensitive: attribute.IsSensitive(),
			}
		}
		surface[resource.resourceTypeName()] = v3ResourceSurface{
			Version: response.Schema.Version, Attributes: attributes,
		}
	}
	return surface
}

// TestV3TerraformSchemaEvolutionRuleHoldsTheSurface is the mechanical half of
// the evolution rule.
//
// The committed baseline is a FLOOR, not a snapshot: an additive change needs
// no edit here and passes, and a breaking one fails naming the resource type
// that would have to be minted instead. What the test cannot decide — whether
// an attribute that kept its name, type, and flags kept its MEANING — is stated
// in v3_schema_evolution.go and carried by review.
func TestV3TerraformSchemaEvolutionRuleHoldsTheSurface(t *testing.T) {
	t.Parallel()
	current := v3CurrentSurface(t)
	if os.Getenv("TAKOFORM_WRITE_SCHEMA_BASELINE") == "1" {
		raw, err := json.MarshalIndent(current, "", "  ")
		if err != nil {
			t.Fatal(err)
		}
		if err := os.MkdirAll(filepath.Dir(v3SurfaceBaselinePath), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(v3SurfaceBaselinePath, append(raw, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Fatalf("rewrote %s; re-run without TAKOFORM_WRITE_SCHEMA_BASELINE", v3SurfaceBaselinePath)
	}
	raw, err := os.ReadFile(v3SurfaceBaselinePath)
	if err != nil {
		t.Fatalf("read the committed surface baseline: %v", err)
	}
	var baseline map[string]v3ResourceSurface
	if err := json.Unmarshal(raw, &baseline); err != nil {
		t.Fatalf("decode the committed surface baseline: %v", err)
	}
	if len(baseline) == 0 {
		t.Fatal("the committed surface baseline is empty")
	}
	for _, resourceType := range v3SortedSurfaceKeys(baseline) {
		before := baseline[resourceType]
		after, kept := current[resourceType]
		if !kept {
			if resourceType == "takoform_edge_object_bucket" {
				// ObjectBucket was withdrawn from the current versionless family
				// and Provider 3 registration. Provider 2.1.1 remains the immutable
				// historical implementation; this major line does not reinterpret
				// that type as a different Form.
				continue
			}
			t.Errorf(
				"%s no longer exists. Removing a Terraform resource type breaks every configuration that "+
					"names it; keep it serving the state written under its own codec and mint a new type for the "+
					"new contract.",
				resourceType,
			)
			continue
		}
		if after.Version < before.Version {
			t.Errorf("%s schema version went backwards, %d to %d", resourceType, before.Version, after.Version)
		}
		for _, name := range v3SortedAttributeKeys(before.Attributes) {
			was := before.Attributes[name]
			is, present := after.Attributes[name]
			if !present {
				t.Errorf(
					"%s.%s was removed. Removing an attribute requires a NEW Terraform resource type "+
						"(%s_v2, or a different Form kind); the existing type must keep serving it.",
					resourceType, name, resourceType,
				)
				continue
			}
			if is.Type != was.Type {
				t.Errorf(
					"%s.%s changed type from %s to %s. Retyping an attribute requires a NEW Terraform "+
						"resource type (%s_v2, or a different Form kind).",
					resourceType, name, was.Type, is.Type, resourceType,
				)
			}
			if is.Required && !was.Required {
				t.Errorf(
					"%s.%s became Required. Making an attribute required invalidates every existing "+
						"configuration that omits it, so it requires a NEW Terraform resource type (%s_v2).",
					resourceType, name, resourceType,
				)
			}
			if was.Computed && !is.Computed {
				t.Errorf(
					"%s.%s stopped being Computed. A value the provider no longer writes reads as null in "+
						"every expression that consumes it, so it requires a NEW Terraform resource type (%s_v2).",
					resourceType, name, resourceType,
				)
			}
			if was.Sensitive && !is.Sensitive {
				t.Errorf(
					"%s.%s stopped being Sensitive, which would start printing a value the provider "+
						"previously withheld.",
					resourceType, name,
				)
			}
		}
		for _, name := range v3SortedAttributeKeys(after.Attributes) {
			if _, existed := before.Attributes[name]; existed {
				continue
			}
			if after.Attributes[name].Required {
				t.Errorf(
					"%s.%s was added as Required, which invalidates every existing configuration. "+
						"An addition to an existing resource type must be Optional or Computed.",
					resourceType, name,
				)
			}
		}
	}
	for _, resourceType := range v3SortedSurfaceKeys(current) {
		if _, existed := baseline[resourceType]; !existed {
			t.Logf("%s is new to this build and is not yet in the baseline floor", resourceType)
		}
	}
}

func v3SortedSurfaceKeys(surface map[string]v3ResourceSurface) []string {
	out := make([]string, 0, len(surface))
	for key := range surface {
		out = append(out, key)
	}
	sort.Strings(out)
	return out
}

func v3SortedAttributeKeys(attributes map[string]v3AttributeSurface) []string {
	out := make([]string, 0, len(attributes))
	for key := range attributes {
		out = append(out, key)
	}
	sort.Strings(out)
	return out
}

// TestV3EverySchemaCarriesTheLaneVersionAndAnUpgrader proves the mechanism the
// rule depends on exists on every resource of the lane, not only where it is
// currently needed.
func TestV3EverySchemaCarriesTheLaneVersionAndAnUpgrader(t *testing.T) {
	t.Parallel()
	ctx := context.Background()
	for _, form := range edgeformcatalog.Forms {
		resource := v3Provider3CurrentResourceHarness(t, form, "", nil, v3Codecs())
		var response frameworkresource.SchemaResponse
		resource.Schema(ctx, frameworkresource.SchemaRequest{}, &response)
		if response.Schema.Version != v3SchemaVersion {
			t.Errorf("%s schema version = %d, want %d", form.Kind, response.Schema.Version, v3SchemaVersion)
		}
		upgraders := resource.UpgradeState(ctx)
		if len(upgraders) != int(v3SchemaVersion) {
			t.Errorf("%s registers %d state upgraders, want one per earlier version (%d)",
				form.Kind, len(upgraders), v3SchemaVersion)
		}
		for version := int64(0); version < v3SchemaVersion; version++ {
			upgrader, registered := upgraders[version]
			if !registered {
				t.Errorf("%s registers no upgrader from schema version %d", form.Kind, version)
				continue
			}
			if upgrader.PriorSchema == nil || upgrader.StateUpgrader == nil {
				t.Errorf("%s upgrader from version %d is incomplete", form.Kind, version)
			}
		}
	}
}

// TestV3StateUpgraderRoundTrip drives the registered upgrader over real state
// and proves it loses nothing.
func TestV3StateUpgraderRoundTrip(t *testing.T) {
	host := newV3FakeHost(t)
	host.assignedOutputs = v3EndpointOutputs()
	resource := v3TestFormResource(t, "WorkerEndpoint", newV3TestProviderData(t, host))
	ctx := context.Background()
	schemaResponse := v3SchemaOf(t, resource)

	plan := v3PlanWith(t, ctx, schemaResponse, map[string]attr.Value{
		"name":   types.StringValue("worker-endpoint"),
		"worker": types.StringValue("module-worker"),
	})
	createResponse := frameworkresource.CreateResponse{
		State: tfsdk.State{Schema: schemaResponse.Schema, Raw: v3EmptyRaw(t, ctx, schemaResponse)},
	}
	resource.Create(ctx, frameworkresource.CreateRequest{Plan: plan}, &createResponse)
	if createResponse.Diagnostics.HasError() {
		t.Fatalf("create: %v", createResponse.Diagnostics)
	}

	upgrader, registered := resource.UpgradeState(ctx)[0]
	if !registered {
		t.Fatal("no upgrader is registered from schema version 0")
	}
	priorSchema, ok := any(*upgrader.PriorSchema).(schema.Schema)
	if !ok {
		t.Fatal("the registered prior schema is not a resource schema")
	}
	if priorSchema.Version != 0 {
		t.Fatalf("prior schema version = %d, want 0", priorSchema.Version)
	}
	request := frameworkresource.UpgradeStateRequest{
		State: &tfsdk.State{Schema: priorSchema, Raw: createResponse.State.Raw},
	}
	response := frameworkresource.UpgradeStateResponse{
		State: tfsdk.State{Schema: schemaResponse.Schema, Raw: v3EmptyRaw(t, ctx, schemaResponse)},
	}
	upgrader.StateUpgrader(ctx, request, &response)
	if response.Diagnostics.HasError() {
		t.Fatalf("upgrade: %v", response.Diagnostics)
	}
	if !response.State.Raw.Equal(createResponse.State.Raw) {
		t.Fatal("the version 0 upgrade changed state; it is declared as a whole-value carry")
	}
	// And the upgraded value is still readable through the CURRENT schema, which
	// is the whole point of a round trip.
	for name, want := range map[string]string{
		"name":     "worker-endpoint",
		"worker":   "module-worker",
		"hostname": v3TestEndpointHostname,
		"url":      v3TestEndpointURL,
	} {
		if got := v3StateString(t, ctx, response.State, name).ValueString(); got != want {
			t.Errorf("upgraded state %s = %q, want %q", name, got, want)
		}
	}
	// A missing prior state is a fault, not a silent empty upgrade.
	empty := frameworkresource.UpgradeStateResponse{
		State: tfsdk.State{Schema: schemaResponse.Schema, Raw: v3EmptyRaw(t, ctx, schemaResponse)},
	}
	upgrader.StateUpgrader(ctx, frameworkresource.UpgradeStateRequest{}, &empty)
	if !empty.Diagnostics.HasError() {
		t.Fatal("an upgrade with no prior state was accepted")
	}
}

