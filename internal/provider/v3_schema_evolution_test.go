// TestV3FormLineAdvanceKeepsOneTerraformResourceType is the behavioural half of
// the rule: a Form line that advanced ADDITIVELY keeps one Terraform resource
// type, and that one type serves both identities for their whole lives.
//
// The prior definition version here declares the same outputs and one fewer
// desired field than the current one, which is exactly the additive shape the
// rule permits. Everything a resource can be asked to do is then driven against
// state recorded under the OLD identity — refresh, import, read the outputs it
// published, delete — while a NEW resource is created under the current one.
func TestV3FormLineAdvanceKeepsOneTerraformResourceType(t *testing.T) {
	host := newV3FakeHost(t)
	host.assignedOutputs = v3EndpointOutputs()
	ctx := context.Background()

	current, ok := edgeformcatalog.ByKind("WorkerEndpoint")
	if !ok {
		t.Fatal("WorkerEndpoint is not a declared family Form")
	}
	priorForm := current
	priorForm.DefinitionVersion = v3PriorEndpointRef.DefinitionVersion
	resource := v3ResourceWithSecondDefinitionVersion(
		t, "WorkerEndpoint", newV3TestProviderData(t, host), v3PriorEndpointRef, priorForm, false,
	)
	schemaResponse := v3SchemaOf(t, resource)
	if got := len(schemaResponse.Schema.Attributes); got == 0 {
		t.Fatal("the resource type serving two definition versions has no attributes")
	}

	// A NEW resource is created under the current default identity.
	plan := v3PlanWith(t, ctx, schemaResponse, map[string]attr.Value{
		"name":   types.StringValue("worker-endpoint"),
		"worker": types.StringValue("module-worker"),
	})
	createResponse := frameworkresource.CreateResponse{
		State: tfsdk.State{Schema: schemaResponse.Schema, Raw: v3EmptyRaw(t, ctx, schemaResponse)},
	}
	resource.Create(ctx, frameworkresource.CreateRequest{Plan: plan}, &createResponse)
	if createResponse.Diagnostics.HasError() {
		t.Fatalf("create under the current identity: %v", createResponse.Diagnostics)
	}
	if got := v3StateString(t, ctx, createResponse.State, "form_definition_version").ValueString(); got == v3PriorEndpointRef.DefinitionVersion {
		t.Fatal("a new resource was created under the PRIOR definition version")
	}

	// Existing state recorded under the OLD identity refreshes through the same
	// resource type, and publishes the outputs that definition declared.
	priorState := v3SeedStateRef(
		t, ctx, tfsdk.State{Schema: schemaResponse.Schema, Raw: createResponse.State.Raw}, v3PriorEndpointRef,
	)
	readResponse := frameworkresource.ReadResponse{State: priorState}
	resource.Read(ctx, frameworkresource.ReadRequest{State: priorState}, &readResponse)
	if readResponse.Diagnostics.HasError() {
		t.Fatalf("refresh of state recorded under the prior identity: %v", readResponse.Diagnostics)
	}
	if got := v3StateString(t, ctx, readResponse.State, "form_definition_version").ValueString(); got != v3PriorEndpointRef.DefinitionVersion {
		t.Fatalf("a refresh rebound the resource onto %q", got)
	}
	for name, want := range map[string]string{
		"hostname": v3TestEndpointHostname,
		"url":      v3TestEndpointURL,
	} {
		if got := v3StateString(t, ctx, readResponse.State, name).ValueString(); got != want {
			t.Errorf("prior-identity refresh output %s = %q, want the preserved %q", name, got, want)
		}
	}

	// The OLD exact FormRef imports through the same resource type.
	importID, err := json.Marshal(map[string]string{
		"space":             "prod",
		"apiVersion":        v3PriorEndpointRef.APIVersion,
		"kind":              v3PriorEndpointRef.Kind,
		"definitionVersion": v3PriorEndpointRef.DefinitionVersion,
		"schemaDigest":      v3PriorEndpointRef.SchemaDigest,
		"name":              "worker-endpoint",
	})
	if err != nil {
		t.Fatal(err)
	}
	importResponse := frameworkresource.ImportStateResponse{
		State: tfsdk.State{Schema: schemaResponse.Schema, Raw: v3EmptyRaw(t, ctx, schemaResponse)},
	}
	resource.ImportState(ctx, frameworkresource.ImportStateRequest{ID: string(importID)}, &importResponse)
	if importResponse.Diagnostics.HasError() {
		t.Fatalf("import of the prior exact FormRef: %v", importResponse.Diagnostics)
	}
	if got := v3StateString(t, ctx, importResponse.State, "form_definition_version").ValueString(); got != v3PriorEndpointRef.DefinitionVersion {
		t.Fatalf("import bound the resource to %q, want the named prior identity", got)
	}

	// And the OLD resource deletes under its own identity.
	before := len(host.resourceQueries)
	deleteResponse := frameworkresource.DeleteResponse{State: readResponse.State}
	resource.Delete(ctx, frameworkresource.DeleteRequest{State: readResponse.State}, &deleteResponse)
	if deleteResponse.Diagnostics.HasError() {
		t.Fatalf("delete under the prior identity: %v", deleteResponse.Diagnostics)
	}
	if len(host.resourceQueries) != before+1 {
		t.Fatalf("delete drove %d host queries, want one", len(host.resourceQueries)-before)
	}
	query := host.resourceQueries[len(host.resourceQueries)-1]
	if !strings.HasPrefix(query, "DELETE ") || !strings.Contains(query, v3PriorEndpointRef.SchemaDigest) {
		t.Fatalf("delete addressed %q, want the prior identity %q", query, v3PriorEndpointRef.SchemaDigest)
	}
}

// TestV3DerivedRevisionNamesAreDeterministicAndDistinct pins the two properties
// the derived name has to have to be usable as an identity.
func TestV3DerivedRevisionNamesAreDeterministicAndDistinct(t *testing.T) {
	t.Parallel()
	for _, form := range edgeformcatalog.Forms {
		resource := v3Provider3CurrentResourceHarness(t, form, "", nil, v3Codecs())
		if (form.Role == model.RoleRevision) != resource.derivesRevisionName() {
			t.Errorf("%s derives a revision name = %v, want it exactly for the revision role",
				form.Kind, resource.derivesRevisionName())
		}
	}
	bundleForm := mustForm(t, "WorkerBundle")
	versionForm := mustForm(t, "WorkerVersion")
	bundle := v3Provider3CurrentResourceHarness(t, bundleForm, "", nil, v3Codecs())
	version := v3Provider3CurrentResourceHarness(t, versionForm, "", nil, v3Codecs())
	digest := "sha256:" + strings.Repeat("ab", 32)
	first, ok := bundle.v3RevisionNameFromSpec(map[string]any{"manifestDigest": digest}, v3TestRevisionOwner)
	if !ok || !strings.HasPrefix(first, "bundle-") {
		t.Fatalf("bundle derived %q, want a bundle- name", first)
	}
	again, _ := bundle.v3RevisionNameFromSpec(map[string]any{"manifestDigest": digest}, v3TestRevisionOwner)
	if again != first {
		t.Fatalf("the same content derived %q then %q", first, again)
	}
	other, _ := bundle.v3RevisionNameFromSpec(map[string]any{
		"manifestDigest": "sha256:" + strings.Repeat("cd", 32),
	}, v3TestRevisionOwner)
	if other == first {
		t.Fatalf("different content derived the same name %q", first)
	}
	spec := map[string]any{
		"worker":   map[string]any{"apiVersion": edgeformcatalog.Family.APIVersion(), "kind": "ModuleWorker", "name": "counter"},
		"bundle":   map[string]any{"apiVersion": edgeformcatalog.Family.APIVersion(), "kind": "WorkerBundle", "name": first},
		"handlers": []string{"fetch"},
	}
	versionName, ok := version.v3RevisionNameFromSpec(spec, v3TestRevisionOwner)
	if !ok || !strings.HasPrefix(versionName, "version-") {
		t.Fatalf("version derived %q, want a version- name", versionName)
	}
	portable := regexp.MustCompile(model.PatternResourceName)
	for _, name := range []string{first, versionName} {
		if !portable.MatchString(name) {
			t.Fatalf("derived name %q is not a portable resource name", name)
		}
	}
	spec["handlers"] = []string{"fetch", "scheduled"}
	moved, _ := version.v3RevisionNameFromSpec(spec, v3TestRevisionOwner)
	if moved == versionName {
		t.Fatalf("a changed desired spec derived the same version name %q", versionName)
	}
	spec["handlers"] = []string{"fetch"}

	// A second owner of byte-identical content is a second owner. Both kinds
	// have to separate them: a Terraform address has exactly one owner, and a
	// content digest names the bytes rather than who declared them.
	peer := "counter-peer"
	peerBundle, ok := bundle.v3RevisionNameFromSpec(map[string]any{"manifestDigest": digest}, peer)
	if !ok || peerBundle == first {
		t.Fatalf("two owners derived one WorkerBundle name %q from identical content", first)
	}
	peerVersion, ok := version.v3RevisionNameFromSpec(spec, peer)
	if !ok || peerVersion == versionName {
		t.Fatalf("two owners derived one WorkerVersion name %q from an identical spec", versionName)
	}
	for _, name := range []string{peerBundle, peerVersion} {
		if !portable.MatchString(name) {
			t.Fatalf("derived name %q is not a portable resource name", name)
		}
	}
	// A derived name is still a function of the content: the owner is folded in
	// beside the content digest, never over it.
	if !strings.HasPrefix(peerBundle, "bundle-"+strings.TrimPrefix(digest, "sha256:")[:v3RevisionNameDigestLength]+"-") {
		t.Fatalf("the owner overwrote the content half of %q", peerBundle)
	}
	// No owner, no derived name. The provider refuses rather than minting one
	// two owners can both reach.
	if _, ok := bundle.v3RevisionNameFromSpec(map[string]any{"manifestDigest": digest}, ""); ok {
		t.Fatal("a revision name was derived without an owner")
	}
	// The longest owner the provider accepts still derives a portable name.
	longest, ok := bundle.v3RevisionNameFromSpec(
		map[string]any{"manifestDigest": digest}, strings.Repeat("z", model.ResourceNameMaxLength))
	if !ok || !portable.MatchString(longest) {
		t.Fatalf("the longest owner derived %q, which is not a portable resource name", longest)
	}
}

func mustForm(t *testing.T, kind string) model.Form {
	t.Helper()
	form, ok := edgeformcatalog.ByKind(kind)
	if !ok {
		t.Fatalf("%s is not a declared family Form", kind)
	}
	return form
}

// TestV3AttributeSurfaceRendersDeterministically guards the baseline's own
// comparability: a surface whose rendering is not stable would fail the floor
// test for reasons that have nothing to do with the rule.
func TestV3AttributeSurfaceRendersDeterministically(t *testing.T) {
	t.Parallel()
	first, err := json.Marshal(v3CurrentSurface(t))
	if err != nil {
		t.Fatal(err)
	}
	second, err := json.Marshal(v3CurrentSurface(t))
	if err != nil {
		t.Fatal(err)
	}
	if string(first) != string(second) {
		t.Fatal("the derived Terraform surface is not deterministic")
	}
	if !strings.Contains(string(first), fmt.Sprintf("%q", "takoform_worker_version")) {
		t.Fatal("the derived surface does not carry the lane's resource types")
	}
}
